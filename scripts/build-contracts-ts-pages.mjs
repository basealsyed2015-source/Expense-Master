/**
 * One-off generator: reads legacy contracts-module/*.html, applies production patches,
 * writes src/contracts-module-pages/generated/*.ts with escaped template literals.
 * Run: node scripts/build-contracts-ts-pages.mjs
 */
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.join(__dirname, '..')
const cssPath = path.join(root, 'src/contracts-module/css/style.css')
const outDir = path.join(root, 'src/contracts-module-pages/generated')

const contractsModuleCss = fs.readFileSync(cssPath, 'utf8')

/** Keep in sync with LEGACY_ASSETS_QUERY in src/contracts-module-pages.ts */
const ASSETS_VERSION = '20260713'

function patchHtml(html) {
  let h = html.replace(/\r\n/g, '\n')
  h = h
    .replace(/\s*<link rel="stylesheet" href="css\/style\.css"\s*\/?>/gi, '')
    .replace(/\s*<link rel="stylesheet" href='css\/style\.css'\s*\/?>/gi, '')
    .replace(/\s*<link rel="stylesheet" href="\/contracts-module\/css\/style\.css"\s*\/?>/gi, '')
    .replace(/\s*<link rel="stylesheet" href='\/contracts-module\/css\/style\.css'\s*\/?>/gi, '')
  const styleBlock = `\n  <style id="contracts-module-styles">\n${contractsModuleCss}\n  </style>\n`
  if (!h.includes('id="contracts-module-styles"')) {
    h = h.replace('<head>', `<head>${styleBlock}`)
  }
  h = h.replace(/src="js\/app\.js"/g, `src="/contracts-module/js/app.js?v=${ASSETS_VERSION}"`)
  h = h.replace(/src="js\/dashboard\.js"/g, `src="/contracts-module/js/dashboard.js?v=${ASSETS_VERSION}"`)
  h = h.replace(/new-contract\.html\?template=/g, '/admin/contracts/new?template=')
  h = h.replace(/new-contract\.html\?edit=/g, '/admin/contracts/new?edit=')
  h = h.replace(/contract-view\.html\?id=/g, '/admin/contracts/view?id=')
  h = h.replace(/notes\.html\?/g, '/admin/contracts/notes?')
  h = h.replace(/href="index\.html"/g, 'href="/admin/contracts"')
  h = h.replace(/href="contracts\.html"/g, 'href="/admin/contracts/list"')
  h = h.replace(/href="new-contract\.html"/g, 'href="/admin/contracts/new"')
  h = h.replace(/href="templates\.html"/g, 'href="/admin/contracts/templates"')
  h = h.replace(/href="notes\.html"/g, 'href="/admin/contracts/notes"')
  h = h.replace(/href="archive\.html"/g, 'href="/admin/contracts/archive"')
  h = h.replace(/href="settings\.html"/g, 'href="/admin/contracts/settings"')
  h = h.replace(/window\.location\.href = 'contracts\.html'/g, "window.location.href = '/admin/contracts/list'")
  h = h.replace(/window\.location\.href = `contracts\.html`/g, 'window.location.href = `/admin/contracts/list`')
  h = h.replace(/`contracts\.html`/g, '`/admin/contracts/list`')
  h = h.replace(/`new-contract\.html\?edit=/g, '`/admin/contracts/new?edit=')
  h = h.replace(/`notes\.html\?search=/g, '`/admin/contracts/notes?search=')
  h = h.replace(/`contract-view\.html\?id=/g, '`/admin/contracts/view?id=')
  return h
}

function escapeForTsTemplate(html) {
  return html
    .replace(/\\/g, '\\\\')
    .replace(/`/g, '\\`')
    .replace(/\$\{/g, '\\${')
}

const pages = [
  { file: 'index.html', exportName: 'contractsDashboardPage' },
  { file: 'contracts.html', exportName: 'contractsListPage' },
  { file: 'new-contract.html', exportName: 'contractsNewPage' },
  { file: 'templates.html', exportName: 'contractsTemplatesPage' },
]

fs.mkdirSync(outDir, { recursive: true })

for (const { file, exportName } of pages) {
  const srcPath = path.join(root, 'src/contracts-module', file)
  const raw = fs.readFileSync(srcPath, 'utf8')
  const patched = patchHtml(raw)
  const escaped = escapeForTsTemplate(patched)
  const out = `/**
 * Generated by scripts/build-contracts-ts-pages.mjs — do not edit by hand.
 * Source: src/contracts-module/${file}
 */
export const ${exportName} = \`${escaped}\`
`
  const outPath = path.join(outDir, `${exportName}.ts`)
  fs.writeFileSync(outPath, out, 'utf8')
  console.log('Wrote', path.relative(root, outPath))
}

console.log('Done.')
